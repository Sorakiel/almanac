// "Sign in with Almanac" — the HTTP side of the OAuth 2.1 server in
// migrations/0040_oauth.sql. Every decision (client, redirect_uri, scopes,
// codes, refresh rotation, revocation) is made by the oauth_svc_* functions;
// this file parses requests, signs access tokens and speaks OAuth's wire format.
//
//   GET  /authorize  → redirects to the web app's consent modal
//   POST /token      → authorization_code (+ PKCE) and refresh_token grants
//   POST /revoke     → RFC 7009
//   GET  /.well-known/oauth-authorization-server
//
// Access tokens are ES256 JWTs with role `almanac_app`, signed with
// OAUTH_SIGNING_JWK — a private key imported into the project's JWT signing
// keys as a STANDBY key, which is what makes the Data API trust it. Never press
// "Rotate" on that key: Auth would start signing every session with it.
//
// Deploy with verify_jwt off (config.toml): a browser opening /authorize has
// no token, and /token authenticates the client itself.
//
// Function secrets:
//   OAUTH_SIGNING_JWK — the private JWK (with kid), as generated by
//                       `supabase gen signing-key --algorithm ES256`
//   APP_URL           — web app origin that hosts the consent modal
// SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are injected automatically.

import { createClient } from 'https://esm.sh/@supabase/supabase-js@2'
import { importJWK, jwtVerify, SignJWT, type JWK } from 'npm:jose@5.9.6'

const ACCESS_TOKEN_SECONDS = 3600

const SUPABASE_URL = Deno.env.get('SUPABASE_URL') ?? ''
const ISSUER = `${SUPABASE_URL}/functions/v1/oauth`
const APP_URL = (Deno.env.get('APP_URL') ?? '').replace(/\/$/, '')

const db = createClient(SUPABASE_URL, Deno.env.get('SUPABASE_SERVICE_ROLE_KEY') ?? '', {
  auth: { persistSession: false },
})

type SigningJwk = JWK & { kid?: string }
type Key = Awaited<ReturnType<typeof importJWK>>

// Imported on first use, so a missing secret fails the token request with a
// logged error instead of the whole function at boot.
let keys: Promise<{ kid: string | undefined; sign: Key; verify: Key }> | null = null
function signingKeys(): Promise<{ kid: string | undefined; sign: Key; verify: Key }> {
  keys ??= (async () => {
    const raw = Deno.env.get('OAUTH_SIGNING_JWK')
    if (!raw) throw new Error('OAUTH_SIGNING_JWK is not set')
    const parsed = JSON.parse(raw) as SigningJwk | SigningJwk[]
    const jwk = Array.isArray(parsed) ? parsed[0] : parsed
    const { d: _private, key_ops: _ops, ...publicJwk } = jwk
    return {
      kid: jwk.kid,
      sign: await importJWK({ ...jwk, key_ops: ['sign'] }, 'ES256'),
      verify: await importJWK({ ...publicJwk, key_ops: ['verify'] }, 'ES256'),
    }
  })()
  keys.catch(() => (keys = null))
  return keys
}

const CORS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, content-type',
  'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
}

interface SvcError {
  error: string
  error_description?: string
  redirect?: boolean
}

interface IssuedGrant {
  user_id: string
  email: string | null
  client_id: string
  scopes: string[]
  refresh_token: string
}

function json(body: unknown, status = 200, extra: Record<string, string> = {}): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: {
      ...CORS,
      'Content-Type': 'application/json',
      'Cache-Control': 'no-store',
      Pragma: 'no-cache',
      ...extra,
    },
  })
}

function oauthError(e: SvcError): Response {
  const status = e.error === 'invalid_client' ? 401 : 400
  const extra: Record<string, string> =
    status === 401 ? { 'WWW-Authenticate': 'Basic realm="almanac"' } : {}
  return json({ error: e.error, error_description: e.error_description }, status, extra)
}

function isError(value: unknown): value is SvcError {
  return typeof value === 'object' && value !== null && 'error' in value
}

async function rpc<T>(name: string, args: Record<string, unknown>): Promise<T> {
  const { data, error } = await db.rpc(name, args)
  if (error) throw new Error(`${name}: ${error.message}`)
  return data as T
}

/** Form or JSON body, as RFC 6749 allows either from real clients. */
async function readParams(req: Request): Promise<URLSearchParams> {
  const type = req.headers.get('content-type') ?? ''
  if (type.includes('application/json')) {
    const body = (await req.json()) as Record<string, unknown>
    return new URLSearchParams(
      Object.entries(body)
        .filter(([, v]) => typeof v === 'string')
        .map(([k, v]) => [k, v as string]),
    )
  }
  return new URLSearchParams(await req.text())
}

/** client_secret_basic or client_secret_post; public clients send only client_id. */
function clientCredentials(
  req: Request,
  params: URLSearchParams,
): { id: string; secret: string | null } {
  const header = req.headers.get('authorization') ?? ''
  if (header.toLowerCase().startsWith('basic ')) {
    const decoded = atob(header.slice(6).trim())
    const colon = decoded.indexOf(':')
    return {
      id: decodeURIComponent(decoded.slice(0, colon)),
      secret: decodeURIComponent(decoded.slice(colon + 1)),
    }
  }
  return { id: params.get('client_id') ?? '', secret: params.get('client_secret') }
}

async function tokenResponse(grant: IssuedGrant): Promise<Response> {
  const { kid, sign } = await signingKeys()
  const scope = grant.scopes.join(' ')
  const accessToken = await new SignJWT({
    role: 'almanac_app',
    client_id: grant.client_id,
    scope,
  })
    .setProtectedHeader({ alg: 'ES256', kid, typ: 'JWT' })
    .setIssuer(ISSUER)
    .setSubject(grant.user_id)
    .setAudience('authenticated')
    .setIssuedAt()
    .setExpirationTime(`${ACCESS_TOKEN_SECONDS}s`)
    .setJti(crypto.randomUUID())
    .sign(sign)

  return json({
    access_token: accessToken,
    token_type: 'bearer',
    expires_in: ACCESS_TOKEN_SECONDS,
    refresh_token: grant.refresh_token,
    scope,
    // Not part of RFC 6749, which allows extra fields: who signed in, so the
    // app can show it without a second request.
    account: { id: grant.user_id, email: grant.email },
  })
}

function plainError(status: number, message: string): Response {
  return new Response(`Almanac sign-in: ${message}`, {
    status,
    headers: { 'Content-Type': 'text/plain; charset=utf-8' },
  })
}

async function authorize(url: URL): Promise<Response> {
  const q = url.searchParams
  const redirectUri = q.get('redirect_uri')
  const state = q.get('state')
  const result = await rpc<SvcError | { request_id: string }>('oauth_svc_authorize', {
    p_client_id: q.get('client_id'),
    p_redirect_uri: redirectUri,
    p_scope: q.get('scope'),
    p_code_challenge: q.get('code_challenge'),
    p_code_challenge_method: q.get('code_challenge_method'),
    p_state: state,
  })

  let error: SvcError | null = isError(result) ? result : null
  if (!error && q.get('response_type') !== 'code') {
    error = {
      error: 'unsupported_response_type',
      error_description: 'response_type must be code',
      redirect: true,
    }
  }
  if (error) {
    // An unverified redirect_uri never gets a redirect (RFC 6749 §4.1.2.1).
    if (!error.redirect || !redirectUri)
      return plainError(400, error.error_description ?? error.error)
    const back = new URL(redirectUri)
    back.searchParams.set('error', error.error)
    if (error.error_description) back.searchParams.set('error_description', error.error_description)
    if (state) back.searchParams.set('state', state)
    return Response.redirect(back.toString(), 302)
  }

  const requestId = (result as { request_id: string }).request_id
  return Response.redirect(`${APP_URL}/?oauth_request=${requestId}`, 302)
}

async function token(req: Request): Promise<Response> {
  const params = await readParams(req)
  const client = clientCredentials(req, params)
  const grantType = params.get('grant_type')

  let result: SvcError | IssuedGrant
  if (grantType === 'authorization_code') {
    result = await rpc('oauth_svc_exchange_code', {
      p_client_id: client.id,
      p_client_secret: client.secret,
      p_code: params.get('code'),
      p_redirect_uri: params.get('redirect_uri'),
      p_code_verifier: params.get('code_verifier'),
    })
  } else if (grantType === 'refresh_token') {
    result = await rpc('oauth_svc_refresh', {
      p_client_id: client.id,
      p_client_secret: client.secret,
      p_refresh_token: params.get('refresh_token'),
    })
  } else {
    return oauthError({ error: 'unsupported_grant_type' })
  }

  return isError(result) ? oauthError(result) : tokenResponse(result)
}

async function revoke(req: Request): Promise<Response> {
  const params = await readParams(req)
  const client = clientCredentials(req, params)
  const tokenValue = params.get('token') ?? ''

  // A JWT is an access token: verify it is ours and the caller's, then drop
  // the grant behind it. Anything else is tried as a refresh token.
  if (tokenValue.split('.').length === 3) {
    try {
      const { payload } = await jwtVerify(tokenValue, (await signingKeys()).verify, {
        issuer: ISSUER,
      })
      if (payload.client_id === client.id && typeof payload.sub === 'string') {
        const result = await rpc<SvcError | Record<string, never>>('oauth_svc_revoke_access', {
          p_client_id: client.id,
          p_client_secret: client.secret,
          p_user: payload.sub,
        })
        if (isError(result)) return oauthError(result)
      }
    } catch {
      // Expired or foreign: nothing to revoke, and RFC 7009 says answer 200.
    }
    return json({})
  }

  const result = await rpc<SvcError | Record<string, never>>('oauth_svc_revoke', {
    p_client_id: client.id,
    p_client_secret: client.secret,
    p_token: tokenValue,
  })
  return isError(result) ? oauthError(result) : json({})
}

function metadata(): Response {
  return json({
    issuer: ISSUER,
    authorization_endpoint: `${ISSUER}/authorize`,
    token_endpoint: `${ISSUER}/token`,
    revocation_endpoint: `${ISSUER}/revoke`,
    response_types_supported: ['code'],
    grant_types_supported: ['authorization_code', 'refresh_token'],
    code_challenge_methods_supported: ['S256'],
    token_endpoint_auth_methods_supported: ['none', 'client_secret_basic', 'client_secret_post'],
    revocation_endpoint_auth_methods_supported: [
      'none',
      'client_secret_basic',
      'client_secret_post',
    ],
    scopes_supported: ['habits:read', 'habits:write'],
  })
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response(null, { status: 204, headers: CORS })
  const url = new URL(req.url)
  const route = url.pathname.replace(/^(\/functions\/v1)?\/oauth/, '') || '/'

  try {
    if (req.method === 'GET' && route === '/authorize') return await authorize(url)
    if (req.method === 'POST' && route === '/token') return await token(req)
    if (req.method === 'POST' && route === '/revoke') return await revoke(req)
    if (req.method === 'GET' && route === '/.well-known/oauth-authorization-server')
      return metadata()
    return json({ error: 'not_found' }, 404)
  } catch (err) {
    console.error(err)
    return route === '/authorize'
      ? plainError(500, 'server error')
      : json({ error: 'server_error' }, 500)
  }
})
